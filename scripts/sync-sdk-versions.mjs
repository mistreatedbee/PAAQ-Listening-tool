#!/usr/bin/env node
/**
 * Propagate packages/sdk-versions.json to every consumer:
 * package manifests, SDK source constants, edge snippets, and dashboard.
 *
 * Run before every SDK publish and whenever latest versions change.
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const CATALOG_PATH = path.join(ROOT, 'packages/sdk-versions.json')

const catalog = JSON.parse(fs.readFileSync(CATALOG_PATH, 'utf8'))

/** @type {Record<string, string>} */
const LATEST = {}
for (const [platform, info] of Object.entries(catalog.platforms)) {
  LATEST[platform] = info.version
}

/** @type {Record<string, string>} */
const PACKAGES = {}
for (const [platform, info] of Object.entries(catalog.platforms)) {
  PACKAGES[platform] = info.package
}

function generateSdkVersionsModule() {
  return `/** AUTO-GENERATED by scripts/sync-sdk-versions.mjs — edit packages/sdk-versions.json instead. */
export const LATEST_SDK_VERSIONS: Record<string, string> = ${JSON.stringify(LATEST, null, 2)}

export const SDK_PACKAGES: Record<string, string> = ${JSON.stringify(PACKAGES, null, 2)}

/** DB connector layers — not npm-installable app SDKs; never compare to web version. */
export const DATABASE_PLATFORMS = new Set([
  'postgres', 'mysql', 'mongodb', 'sqlite', 'redis', 'supabase', 'database',
])

export function isNpmSdkPlatform(platform: string): boolean {
  return !DATABASE_PLATFORMS.has(platform.toLowerCase())
}

/** Synthetic heartbeat rows — not a real SDK install to upgrade. */
export const INTERNAL_SDK_DEVICE_IDS = new Set([
  'events-proxy-backend',
  'db-connector',
])

export function isInternalSdkInstallation(deviceId: string | null | undefined): boolean {
  if (!deviceId) return false
  return INTERNAL_SDK_DEVICE_IDS.has(deviceId)
}

export function isPlaceholderSdkVersion(version: string | null | undefined): boolean {
  const v = (version ?? '').trim().toLowerCase()
  if (!v || v === '0' || v === '0.0.0' || v === 'unknown' || v === 'n/a') return true
  return false
}

export function shouldCheckSdkUpgrade(
  platform: string,
  sdkVersion: string,
  deviceId?: string | null,
): boolean {
  if (!isNpmSdkPlatform(platform)) return false
  if (isInternalSdkInstallation(deviceId)) return false
  if (isPlaceholderSdkVersion(sdkVersion)) return false
  return true
}

export function parseSemver(v: string): [number, number, number] {
  const parts = v.replace(/^v/i, '').split('.').map((n) => parseInt(n, 10) || 0)
  return [parts[0] ?? 0, parts[1] ?? 0, parts[2] ?? 0]
}

export function isSdkOutdated(installed: string, latest: string): boolean {
  const a = parseSemver(installed)
  const b = parseSemver(latest)
  if (a[0] !== b[0]) return a[0] < b[0]
  if (a[1] !== b[1]) return a[1] < b[1]
  return a[2] < b[2]
}

export function latestForPlatform(platform: string): string {
  const key = platform.toLowerCase()
  if (DATABASE_PLATFORMS.has(key)) {
    return LATEST_SDK_VERSIONS[key] ?? '1.0.0'
  }
  return LATEST_SDK_VERSIONS[key] ?? LATEST_SDK_VERSIONS.web
}

export function packageForPlatform(platform: string): string {
  const key = platform.toLowerCase()
  if (DATABASE_PLATFORMS.has(key)) {
    return SDK_PACKAGES[key] ?? '@paaq/sdk-core'
  }
  return SDK_PACKAGES[key] ?? SDK_PACKAGES.web
}

/** Agent-ready prompt for upgrading the PAAQ SDK in a connected project. */
export function buildSdkUpgradePrompt(platform: string, current: string, latest: string): string {
  const pkg = packageForPlatform(platform)
  if (DATABASE_PLATFORMS.has(platform.toLowerCase())) {
    return \`Database connector (\${platform}) reports protocol v\${current}; latest catalog is v\${latest}. Re-test the connection in PAAQ Settings → Database if introspection or knowledge sync looks stale. No npm SDK install is required for database layers.\`
  }
  return \`Upgrade the PAAQ SDK for this project from v\${current} to v\${latest} (\${platform}).

1. Update the package: npm install \${pkg}@\${latest}
2. Ensure init still passes projectId and sdkToken from the PAAQ dashboard Connect page.
3. Verify performance monitoring is enabled (installPerfMonitoring runs after init in v1.2+).
4. Confirm X-SDK-Version header reports \${latest} on sdk-init and heartbeat calls.
5. Run the app and confirm events appear in the PAAQ dashboard within 60 seconds.\`
}

/** Short notification body when a brand-new SDK version ships. */
export function buildSdkReleaseMessage(
  packageName: string,
  version: string,
  platforms: string[],
  releaseNotes?: string,
): string {
  const platformList = platforms.length ? platforms.join(', ') : 'all platforms'
  const notes = releaseNotes ? \` \${releaseNotes}\` : ''
  return \`New SDK release: \${packageName} v\${version} (\${platformList}).\${notes} Copy agent prompt: Upgrade PAAQ SDK to v\${version}. Run npm install \${packageName}@\${version}, re-init with your dashboard SDK token, and verify X-SDK-Version is \${version}.\`
}
`
}

function replaceVersionConst(filePath, version) {
  if (!fs.existsSync(filePath)) return
  const src = fs.readFileSync(filePath, 'utf8')
  let next = src.replace(
    /const SDK_VERSION = ['"][^'"]+['"]/,
    `const SDK_VERSION = '${version}'`,
  )
  if (next === src) {
    next = src.replace(
      /export const SDK_CORE_VERSION = ['"][^'"]+['"]/,
      `export const SDK_CORE_VERSION = '${version}'`,
    )
  }
  if (next === src) {
    console.warn(`warn: no SDK_VERSION const updated in ${filePath}`)
    return
  }
  fs.writeFileSync(filePath, next)
}

function updatePackageJson(pkgPath, version) {
  const abs = path.join(ROOT, pkgPath, 'package.json')
  const pj = JSON.parse(fs.readFileSync(abs, 'utf8'))
  pj.version = version
  fs.writeFileSync(abs, JSON.stringify(pj, null, 2) + '\n')
}

// package.json versions + source constants
for (const [npmName, pkg] of Object.entries(catalog.packages)) {
  updatePackageJson(pkg.path, pkg.version)
  if (pkg.sourceVersionConst) {
    replaceVersionConst(path.join(ROOT, pkg.sourceVersionConst), pkg.version)
  }
  console.log(`synced ${npmName} → v${pkg.version}`)
}

// Edge snippet templates (web platforms share @paaq/web-sdk version)
const webVersion = catalog.packages['@paaq/web-sdk'].version
const snippetsPath = path.join(ROOT, 'apps/api/supabase/functions/_shared/sdk-snippets.ts')
let snippets = fs.readFileSync(snippetsPath, 'utf8')
snippets = snippets.replace(/const SDK_VERSION = '[^']+'/, `const SDK_VERSION = '${webVersion}'`)
fs.writeFileSync(snippetsPath, snippets)

// Generated modules for dashboard + edge functions
const module = generateSdkVersionsModule()
const targets = [
  'apps/dashboard/lib/sdk-versions.ts',
  'apps/api/supabase/functions/_shared/sdk-versions.ts',
]
for (const rel of targets) {
  fs.writeFileSync(path.join(ROOT, rel), module)
}

console.log(`\nSDK versions synced from ${CATALOG_PATH}`)
console.log(`Web SDK latest: v${webVersion}`)
